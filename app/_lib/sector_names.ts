// ───────────────────────────────────────────────────────────────
// getSectorLabel — 안전한 라벨 반환
// 매핑이 없으면 코드를 그대로 노출 ("업종 코드 14")
// ───────────────────────────────────────────────────────────────
export function getSectorLabel(sector: string | null | undefined): string {
  if (!sector || sector.trim() === '') return '업종명 확인 필요';
  const mapped = SECTOR_NAME_MAP[sector];
  if (mapped) return mapped;
  // 숫자만으로 구성된 코드인 경우 "업종 코드 N" 형식
  if (/^\d+$/.test(sector)) return `업종 코드 ${sector}`;
  // 한국어 등 비매핑 텍스트는 그대로 (사이드카가 한국어로 내려준 경우)
  return sector;
}

// ───────────────────────────────────────────────────────────────
// isUnmapped — 매핑 미등록 여부 (UI 안내용)
// ───────────────────────────────────────────────────────────────
export function isSectorUnmapped(sector: string | null | undefined): boolean {
  if (!sector || sector.trim() === '') return true;
  if (sector in SECTOR_NAME_MAP) return false;
  // 숫자 코드는 매핑 미등록
  if (/^\d+$/.test(sector)) return true;
  return false;
}
